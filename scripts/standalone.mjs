import {readFile} from 'node:fs/promises';
import path from 'node:path';

// The project's modules use named imports and const/function/class exports only.
// Reject other module syntax instead of silently generating a broken release.
export async function standalone(root){
 const modules=new Map(),visiting=new Set();
 async function visit(id){
  if(visiting.has(id))throw new Error(`Circular module dependency: ${id}`);
  if(modules.has(id))return;
  visiting.add(id);
  let source=await readFile(path.join(root,id),'utf8');
  const imports=[...source.matchAll(/^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm)];
  for(const match of imports){
   const names=match[1].split(',').map(n=>n.trim());
   if(names.some(n=>!/^[$\w]+$/.test(n)))throw new Error(`Unsupported import in ${id}`);
   const dependency=path.posix.normalize(path.posix.join(path.posix.dirname(id),match[2].split('?')[0]));
   if(!dependency.startsWith('src/'))throw new Error(`Invalid dependency: ${dependency}`);
   await visit(dependency);
   source=source.replace(match[0],`const {${names.join(',')}}=__require(${JSON.stringify(dependency)});\n`);
  }
  const exports=[...source.matchAll(/^export\s+(?:const|function|class)\s+([$\w]+)/gm)].map(m=>m[1]);
  source=source.replace(/^export\s+(?=const |function |class )/gm,'');
  if(/^\s*(?:import|export)\b/m.test(source))throw new Error(`Unsupported module syntax in ${id}`);
  modules.set(id,`${JSON.stringify(id)}:(exports,__require)=>{\n${source}\nObject.assign(exports,{${exports.join(',')}});\n}`);
  visiting.delete(id);
 }
 await visit('src/main.js');
 const script=`(()=>{\n'use strict';\nconst modules={${[...modules.values()].join(',\n')}},cache=Object.create(null);\nfunction __require(id){if(!cache[id]){const exports={};cache[id]=exports;modules[id](exports,__require);}return cache[id];}\n__require("src/main.js");\n})();`;
 const template=await readFile(path.join(root,'templates/page.html'),'utf8');
 const css=await readFile(path.join(root,'style.css'),'utf8');
 if(!template.includes('<script type="module" src=')||!template.includes('<link rel="stylesheet"'))throw new Error('Release template entry points missing');
 return '<!-- Generated by npm run build; edit templates/page.html, src/ and style.css. -->\n'+template
  .replace(/<link rel="stylesheet"[^>]*>/,()=>`<style>${css.replace(/<\/style/gi,'<\\/style')}</style>`)
  .replace(/<script type="module" src="[^"]+"><\/script>/,()=>`<script>${script.replace(/<\/script/gi,'<\\/script')}</script>`);
}
